# association.py
# Association rule mining utilities for lottery combinations.

import pandas as pd
import matplotlib.pyplot as plt
from mlxtend.frequent_patterns import apriori, association_rules
from mlxtend.preprocessing import TransactionEncoder


def prepare_transactions(df, combo_cols):
    """
    Convert lottery combinations into transaction format for Apriori.

    Parameters:
        df (pd.DataFrame): DataFrame containing lottery draws.
        combo_cols (list): List of column names containing the numbers.

    Returns:
        list: List of transactions, where each draw is represented as a list of strings.
    """
    transactions = df[combo_cols].astype(str).values.tolist()
    return transactions


def encode_transactions(transactions):
    """
    Encode transactions into a boolean one-hot DataFrame suitable for Apriori.

    Parameters:
        transactions (list): List of transactions (each transaction is a list of items).

    Returns:
        pd.DataFrame: Boolean-encoded DataFrame where each column represents an item.
    """
    te = TransactionEncoder()
    te_array = te.fit(transactions).transform(transactions)
    df_encoded = pd.DataFrame(te_array, columns=te.columns_)
    return df_encoded


def apply_apriori(df_encoded, min_support=0.01):
    """
    Apply the Apriori algorithm to discover frequent itemsets.

    Parameters:
        df_encoded (pd.DataFrame): Boolean-encoded transaction DataFrame.
        min_support (float): Minimum support threshold for itemsets.

    Returns:
        pd.DataFrame: Frequent itemsets with support values.
    """
    frequent_itemsets = apriori(df_encoded, min_support=min_support, use_colnames=True)
    return frequent_itemsets


def generate_rules(frequent_itemsets, min_confidence=0.3, min_lift=1.0):
    """
    Generate association rules from frequent itemsets.

    Parameters:
        frequent_itemsets (pd.DataFrame): Frequent itemsets generated by Apriori.
        min_confidence (float): Minimum confidence threshold.
        min_lift (float): Minimum lift threshold.

    Returns:
        pd.DataFrame: Filtered association rules meeting confidence and lift criteria.
    """
    rules = association_rules(frequent_itemsets, metric="lift", min_threshold=min_lift)
    rules = rules[rules["confidence"] >= min_confidence]
    return rules


def plot_lift_distribution(rules):
    """
    Plot the distribution of lift values from association rules.

    Parameters:
        rules (pd.DataFrame): Association rules DataFrame.
    """
    plt.figure(figsize=(8, 5))
    plt.hist(rules["lift"], bins=30, color="purple", edgecolor="black")
    plt.title("Distribution of Lift Values in Association Rules")
    plt.xlabel("Lift")
    plt.ylabel("Frequency")
    plt.tight_layout()
    plt.show()
